export enum MenuSurfaceDataAttributes {
  /**
   * Present when the surface is open.
   */
  open = 'data-open',
  /**
   * Present when the surface is closed.
   */
  closed = 'data-closed',
  /**
   * The surface ID.
   */
  surfaceId = 'data-surface-id',
  /**
   * The depth in the menu hierarchy.
   */
  depth = 'data-depth',
  /**
   * Present when this is a submenu surface.
   */
  submenu = 'data-submenu',
}
