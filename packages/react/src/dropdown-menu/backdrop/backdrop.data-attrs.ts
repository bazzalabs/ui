export enum DropdownMenuBackdropDataAttributes {
  /**
   * Present when the dropdown menu is open.
   */
  open = 'data-open',
  /**
   * Present when the dropdown menu is closed.
   */
  closed = 'data-closed',
  /**
   * Present when the dropdown menu is animating in.
   */
  startingStyle = 'data-starting-style',
  /**
   * Present when the dropdown menu is animating out.
   */
  endingStyle = 'data-ending-style',
}
